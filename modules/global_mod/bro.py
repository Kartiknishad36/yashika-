def _load_extra() -> list:
    lines = list(_BASE)
    base = Path(__file__).parent
    for name in ("bro_part_2.json", "bro_part_3.json", "bro_part_4.json"):
        p = base / name
        if not p.exists():
            continue
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(data, list):
                lines.extend([str(x) for x in data if x])
        except Exception as e:
            print(f"[bro] load {name}: {e}")
    # de-dupe keep order
    seen = set()
    out = []
    for x in lines:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


LINES = _load_extra()
print(f"[bro] loaded {len(LINES)} roast lines")


def _mention(u) -> str:
    if not u:
        return "User"
    name = u.first_name or "User"
    return f'<a href="tg://user?id={u.id}">{name}</a>'


def _pick(mention: str = "") -> str:
    line = random.choice(LINES)
    if mention and "{t}" in line:
        return line.replace("{t}", mention)
    if mention:
        return f"{mention}\n{line}"
    return line


async def _run_spam(client, chat_id: int, mention: str, count: int, delay: float = 0.7):
    ACTIVE[chat_id] = True
    sent = 0
    try:
        for _ in range(count):
            if not ACTIVE.get(chat_id):
                break
            try:
                await client.send_message(chat_id, _pick(mention))
                sent += 1
                await asyncio.sleep(delay)
            except Exception:
                await asyncio.sleep(1.5)
    finally:
        ACTIVE[chat_id] = False
    return sent


